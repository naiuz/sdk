// Builds the AudioWorklet module the client loads: dsp.ts as JavaScript, then the processors. It ships as a string
// constant in src/audio/worklet-module.ts, so an app's bundler, which may rewrite the package's own classes, leaves it
// alone.
//
//   node scripts/worklet-module.mjs           writes src/audio/worklet-module.ts
//   node scripts/worklet-module.mjs --check   fails when that file is out of date
import {readFileSync, writeFileSync} from "node:fs";
import {pathToFileURL} from "node:url";
import ts from "typescript";

const root = new URL("../", import.meta.url);
const output = new URL("src/audio/worklet-module.ts", root);

/** The module's text, from dsp.ts and processors.worklet.js as they are now. */
export function buildWorkletModule() {
    const dsp = readFileSync(new URL("src/audio/dsp.ts", root), "utf8");
    const {outputText} = ts.transpileModule(dsp, {
        compilerOptions: {target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, removeComments: true},
    });
    const processors = readFileSync(new URL("src/audio/processors.worklet.js", root), "utf8");
    return `${outputText.replace(/^export /gm, "").trim()}\n\n${processors.trim()}\n`;
}

/** The TypeScript file that carries the module's text. */
export function moduleFile(text) {
    return [
        "// Generated by scripts/worklet-module.mjs from dsp.ts and processors.worklet.js: run npm run generate after changing either.",
        "// A string built with the package: an app's bundler may rewrite the package's classes, but it leaves a string alone.",
        `export const WORKLET_MODULE = ${JSON.stringify(text)};`,
        "",
    ].join("\n");
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const file = moduleFile(buildWorkletModule());
    if (process.argv.includes("--check")) {
        if (readFileSync(output, "utf8") !== file) {
            console.error("src/audio/worklet-module.ts is out of date: run npm run generate");
            process.exit(1);
        }
    } else {
        writeFileSync(output, file);
    }
}
